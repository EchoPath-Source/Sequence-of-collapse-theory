#!/usr/bin/env python3
"""RM-01E: pre-geometric relational dynamics and model competition.

Toy-model methodology only. This is not evidence for SoCT, emergent spacetime,
or a physical gravity-as-memory mechanism.

The generator receives no coordinates. It starts from a random regular relation
network and evolves it under one of three local rules:

1. memory: accumulated co-exposure from local random-walk propagation guides
   degree-preserving edge swaps;
2. triadic: common-neighbor closure guides the same swaps;
3. random: randomized swaps provide a topology-null control.

Persistent records are then generated by local diffusion on the evolved graph.
The first gate asks whether record overlap reconstructs the evolved relations.
The second gate asks which latent/model class best predicts held-out links in the
coordinate-free evolved network: Euclidean latent spaces, Poincare/hyperbolic,
generic low rank, block models, common-neighbor/small-world, tree/path, or a
degree baseline.

Requires: numpy, networkx, scikit-learn, torch.
"""

from __future__ import annotations

import argparse
import csv
import math
from collections import Counter
from dataclasses import dataclass, asdict
from pathlib import Path

import networkx as nx
import numpy as np
import torch
import torch.nn.functional as F
from sklearn.cluster import SpectralClustering
from sklearn.metrics import roc_auc_score

RULES = ("memory", "triadic", "random")
MODEL_NAMES = (
    "euclid_1", "euclid_2", "euclid_3", "euclid_8",
    "hyperbolic_2", "lowrank_8",
    "block_2", "block_4", "block_8",
    "smallworld_cn", "tree_path", "degree",
)


@dataclass
class TrialRow:
    rule: str
    seed: int
    record_edge_auc: float
    euclid_1: float
    euclid_2: float
    euclid_3: float
    euclid_8: float
    hyperbolic_2: float
    lowrank_8: float
    block_2: float
    block_4: float
    block_8: float
    smallworld_cn: float
    tree_path: float
    degree: float
    clustering: float
    mean_shortest_path: float
    diameter: float
    growth_exponent: float


def transition_matrix(graph: nx.Graph, lazy: float = 0.25) -> np.ndarray:
    n = graph.number_of_nodes()
    w = np.zeros((n, n), dtype=float)
    for u, v in graph.edges():
        w[u, v] = 1.0
        w[v, u] = 1.0
    row_sum = w.sum(axis=1)
    p = np.divide(w, row_sum[:, None], out=np.zeros_like(w), where=row_sum[:, None] > 0)
    return (1.0 - lazy) * p + lazy * np.eye(n)


def source_exposure(p: np.ndarray, source: int, steps: int, decay: float) -> np.ndarray:
    state = np.zeros(len(p), dtype=float)
    state[source] = 1.0
    exposure = np.zeros_like(state)
    for t in range(steps + 1):
        exposure += (decay ** t) * state
        state = state @ p
    return exposure


def guided_double_edge_swap(graph: nx.Graph, score: np.ndarray, rng: np.random.Generator, attempts: int = 50) -> bool:
    edges = list(graph.edges())
    for _ in range(attempts):
        i, j = rng.choice(len(edges), 2, replace=False)
        u, v = edges[int(i)]
        x, y = edges[int(j)]
        if len({u, v, x, y}) < 4:
            continue
        old = float(score[u, v] + score[x, y])
        candidates = [((u, x), (v, y)), ((u, y), (v, x))]
        rng.shuffle(candidates)
        best = None
        best_gain = 0.0
        for e1, e2 in candidates:
            a, b = e1
            c, d = e2
            if graph.has_edge(a, b) or graph.has_edge(c, d):
                continue
            gain = float(score[a, b] + score[c, d] - old)
            if gain > best_gain:
                best = (e1, e2)
                best_gain = gain
        if best is None:
            continue
        graph.remove_edge(u, v)
        graph.remove_edge(x, y)
        graph.add_edge(*best[0])
        graph.add_edge(*best[1])
        if nx.is_connected(graph):
            return True
        graph.remove_edge(*best[0])
        graph.remove_edge(*best[1])
        graph.add_edge(u, v)
        graph.add_edge(x, y)
    return False


def evolve_relations(rule: str, seed: int, n: int, degree: int, epochs: int, swaps_per_epoch: int) -> nx.Graph:
    rng = np.random.default_rng(seed)
    graph = nx.random_regular_graph(degree, n, seed=seed)
    memory = np.zeros((n, n), dtype=float)

    for _ in range(epochs):
        if rule == "memory":
            p = transition_matrix(graph)
            batch = np.zeros((n, n), dtype=float)
            for _ in range(8):
                source = int(rng.integers(n))
                exposure = source_exposure(p, source, steps=6, decay=0.88)
                exposure /= max(float(exposure.max()), 1e-12)
                batch += np.outer(exposure, exposure)
            batch /= 8.0
            memory = 0.92 * memory + 0.08 * batch
            score = memory
        elif rule == "triadic":
            score = np.zeros((n, n), dtype=float)
            neighborhoods = [set(graph.neighbors(i)) for i in range(n)]
            for i in range(n):
                for j in range(i + 1, n):
                    value = len(neighborhoods[i] & neighborhoods[j])
                    score[i, j] = score[j, i] = float(value)
        elif rule == "random":
            raw = rng.random((n, n))
            score = 0.5 * (raw + raw.T)
            np.fill_diagonal(score, 0.0)
        else:
            raise ValueError(rule)

        for _ in range(swaps_per_epoch):
            guided_double_edge_swap(graph, score, rng)

    return graph


def generate_records(graph: nx.Graph, seed: int, replicas: int = 8) -> np.ndarray:
    p = transition_matrix(graph, lazy=0.25)
    n = graph.number_of_nodes()
    exposures = np.vstack([source_exposure(p, s, steps=10, decay=0.90) for s in range(n)])
    probability = 1.0 - np.exp(-1.5 * exposures)
    probability = np.repeat(probability, replicas, axis=1)
    rng = np.random.default_rng(seed + 50_000)
    encoded = rng.random(probability.shape) < probability
    retained = rng.random(probability.shape) < 0.95
    return (encoded & retained).astype(np.int8)


def jaccard_distance(records: np.ndarray) -> np.ndarray:
    r = records.astype(np.int16, copy=False)
    ones = r.sum(axis=1, dtype=float)
    intersection = (r @ r.T).astype(float)
    union = ones[:, None] + ones[None, :] - intersection
    with np.errstate(divide="ignore", invalid="ignore"):
        d = np.where(union > 0, 1.0 - intersection / union, 1.0)
    np.fill_diagonal(d, 0.0)
    return d


def record_edge_auc(graph: nx.Graph, d: np.ndarray, seed: int) -> float:
    positives = list(graph.edges())
    rng = np.random.default_rng(seed + 777)
    negatives = list(nx.non_edges(graph))
    rng.shuffle(negatives)
    negatives = negatives[:len(positives)]
    y = np.r_[np.ones(len(positives)), np.zeros(len(negatives))]
    score = np.r_[
        -np.asarray([d[u, v] for u, v in positives]),
        -np.asarray([d[u, v] for u, v in negatives]),
    ]
    return float(roc_auc_score(y, score))


def split_links(graph: nx.Graph, seed: int, fraction: float = 0.15):
    rng = np.random.default_rng(seed + 12_345)
    train = graph.copy()
    edges = list(graph.edges())
    rng.shuffle(edges)
    target = max(1, int(fraction * len(edges)))
    positive = []
    for u, v in edges:
        if len(positive) >= target:
            break
        train.remove_edge(u, v)
        if nx.is_connected(train):
            positive.append((u, v))
        else:
            train.add_edge(u, v)
    negatives = list(nx.non_edges(graph))
    rng.shuffle(negatives)
    negative = negatives[:len(positive)]
    held = {tuple(sorted(e)) for e in positive + negative}
    pairs, labels = [], []
    n = graph.number_of_nodes()
    for i in range(n):
        for j in range(i + 1, n):
            if (i, j) in held:
                continue
            pairs.append((i, j))
            labels.append(1.0 if train.has_edge(i, j) else 0.0)
    return train, np.asarray(positive), np.asarray(negative), np.asarray(pairs), np.asarray(labels, dtype=float)


def heldout_auc(pos: np.ndarray, neg: np.ndarray, score: np.ndarray) -> float:
    y = np.r_[np.ones(len(pos)), np.zeros(len(neg))]
    values = np.r_[
        np.asarray([score[u, v] for u, v in pos]),
        np.asarray([score[u, v] for u, v in neg]),
    ]
    if np.unique(np.round(values, 12)).size < 2:
        return 0.5
    return float(roc_auc_score(y, values))


def euclidean_latent(pairs, labels, n, dim, steps, seed):
    torch.manual_seed(seed)
    x = torch.nn.Parameter(0.1 * torch.randn(n, dim))
    intercept = torch.nn.Parameter(torch.tensor(0.0))
    raw_beta = torch.nn.Parameter(torch.tensor(0.0))
    opt = torch.optim.Adam([x, intercept, raw_beta], lr=0.05)
    pair = torch.tensor(pairs, dtype=torch.long)
    y = torch.tensor(labels, dtype=torch.float32)
    pos_weight = ((len(y) - y.sum()) / (y.sum() + 1e-9)).detach()
    for _ in range(steps):
        opt.zero_grad()
        dist = torch.linalg.norm(x[pair[:, 0]] - x[pair[:, 1]], dim=1)
        beta = F.softplus(raw_beta) + 1e-4
        logits = intercept - beta * dist
        loss = F.binary_cross_entropy_with_logits(logits, y, pos_weight=pos_weight)
        loss += 1e-3 * (x * x).mean()
        loss.backward()
        opt.step()
    with torch.no_grad():
        score = intercept - (F.softplus(raw_beta) + 1e-4) * torch.cdist(x, x)
    return score.cpu().numpy()


def poincare_coordinates(z: torch.Tensor) -> torch.Tensor:
    norm = torch.linalg.norm(z, dim=1, keepdim=True) + 1e-9
    radius = 0.95 * torch.tanh(norm)
    return radius * z / norm


def hyperbolic_latent(pairs, labels, n, steps, seed):
    torch.manual_seed(seed)
    z = torch.nn.Parameter(0.05 * torch.randn(n, 2))
    intercept = torch.nn.Parameter(torch.tensor(0.0))
    raw_beta = torch.nn.Parameter(torch.tensor(0.0))
    opt = torch.optim.Adam([z, intercept, raw_beta], lr=0.03)
    pair = torch.tensor(pairs, dtype=torch.long)
    y = torch.tensor(labels, dtype=torch.float32)
    pos_weight = ((len(y) - y.sum()) / (y.sum() + 1e-9)).detach()
    for _ in range(steps):
        opt.zero_grad()
        x = poincare_coordinates(z)
        u, v = x[pair[:, 0]], x[pair[:, 1]]
        duv = ((u - v) ** 2).sum(axis=1)
        denom = (1 - (u * u).sum(axis=1)) * (1 - (v * v).sum(axis=1))
        arg = 1 + 2 * duv / torch.clamp(denom, min=1e-6)
        dist = torch.acosh(torch.clamp(arg, min=1 + 1e-6))
        beta = F.softplus(raw_beta) + 1e-4
        logits = intercept - beta * dist
        loss = F.binary_cross_entropy_with_logits(logits, y, pos_weight=pos_weight)
        loss += 1e-3 * (z * z).mean()
        loss.backward()
        opt.step()
    with torch.no_grad():
        x = poincare_coordinates(z)
        u, v = x[:, None, :], x[None, :, :]
        duv = ((u - v) ** 2).sum(axis=2)
        norm2 = (x * x).sum(axis=1)
        denom = (1 - norm2[:, None]) * (1 - norm2[None, :])
        arg = 1 + 2 * duv / torch.clamp(denom, min=1e-6)
        dist = torch.acosh(torch.clamp(arg, min=1 + 1e-6))
        score = intercept - (F.softplus(raw_beta) + 1e-4) * dist
    return score.cpu().numpy()


def lowrank_latent(pairs, labels, n, rank, steps, seed):
    torch.manual_seed(seed)
    x = torch.nn.Parameter(0.1 * torch.randn(n, rank))
    intercept = torch.nn.Parameter(torch.tensor(0.0))
    opt = torch.optim.Adam([x, intercept], lr=0.05)
    pair = torch.tensor(pairs, dtype=torch.long)
    y = torch.tensor(labels, dtype=torch.float32)
    pos_weight = ((len(y) - y.sum()) / (y.sum() + 1e-9)).detach()
    for _ in range(steps):
        opt.zero_grad()
        logits = intercept + (x[pair[:, 0]] * x[pair[:, 1]]).sum(axis=1)
        loss = F.binary_cross_entropy_with_logits(logits, y, pos_weight=pos_weight)
        loss += 1e-3 * (x * x).mean()
        loss.backward()
        opt.step()
    with torch.no_grad():
        return (intercept + x @ x.T).cpu().numpy()


def model_aucs(graph: nx.Graph, seed: int, steps: int) -> dict[str, float]:
    train, pos, neg, pairs, labels = split_links(graph, seed)
    n = graph.number_of_nodes()
    out = {}
    for dim in (1, 2, 3, 8):
        score = euclidean_latent(pairs, labels, n, dim, steps, seed)
        out[f"euclid_{dim}"] = heldout_auc(pos, neg, score)
    out["hyperbolic_2"] = heldout_auc(pos, neg, hyperbolic_latent(pairs, labels, n, steps, seed))
    out["lowrank_8"] = heldout_auc(pos, neg, lowrank_latent(pairs, labels, n, 8, steps, seed))

    adjacency = nx.to_numpy_array(train)
    for k in (2, 4, 8):
        labels_k = SpectralClustering(n_clusters=k, affinity="precomputed", random_state=seed).fit_predict(adjacency + 1e-6 * np.eye(n))
        score = np.zeros((n, n), dtype=float)
        for a in range(k):
            ia = np.where(labels_k == a)[0]
            for b in range(k):
                ib = np.where(labels_k == b)[0]
                vals = adjacency[np.ix_(ia, ib)]
                if a == b and len(ia) > 1:
                    vals = vals[~np.eye(len(ia), dtype=bool)]
                probability = (float(vals.sum()) + 1.0) / (float(vals.size) + 2.0)
                score[np.ix_(ia, ib)] = probability
        out[f"block_{k}"] = heldout_auc(pos, neg, score)

    neighborhoods = [set(train.neighbors(i)) for i in range(n)]
    common = np.zeros((n, n), dtype=float)
    for i in range(n):
        for j in range(i + 1, n):
            common[i, j] = common[j, i] = len(neighborhoods[i] & neighborhoods[j])
    out["smallworld_cn"] = heldout_auc(pos, neg, common)

    paths = dict(nx.all_pairs_shortest_path_length(train))
    tree_score = np.zeros((n, n), dtype=float)
    for i in range(n):
        for j in range(n):
            tree_score[i, j] = -float(paths[i].get(j, n))
    out["tree_path"] = heldout_auc(pos, neg, tree_score)

    degree = dict(train.degree())
    degree_score = np.zeros((n, n), dtype=float)
    for i in range(n):
        for j in range(n):
            degree_score[i, j] = degree[i] * degree[j]
    out["degree"] = heldout_auc(pos, neg, degree_score)
    return out


def growth_exponent(graph: nx.Graph) -> float:
    n = graph.number_of_nodes()
    estimates = []
    for source in graph.nodes():
        distances = nx.single_source_shortest_path_length(graph, source)
        xs, ys = [], []
        for radius in range(1, max(distances.values()) + 1):
            volume = sum(1 for d in distances.values() if d <= radius)
            if 2 <= volume <= 0.60 * n:
                xs.append(math.log(float(radius)))
                ys.append(math.log(float(volume)))
        if len(xs) >= 2:
            estimates.append(float(np.polyfit(xs, ys, 1)[0]))
    return float(np.mean(estimates)) if estimates else float("nan")


def run_trial(rule: str, seed: int, args) -> TrialRow:
    graph = evolve_relations(rule, seed, args.nodes, args.degree, args.epochs, args.swaps_per_epoch)
    records = generate_records(graph, seed, args.replicas)
    d = jaccard_distance(records)
    aucs = model_aucs(graph, seed, args.optim_steps)
    return TrialRow(
        rule=rule,
        seed=seed,
        record_edge_auc=record_edge_auc(graph, d, seed),
        **aucs,
        clustering=float(nx.average_clustering(graph)),
        mean_shortest_path=float(nx.average_shortest_path_length(graph)),
        diameter=float(nx.diameter(graph)),
        growth_exponent=growth_exponent(graph),
    )


def write_rows(rows: list[TrialRow], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(asdict(rows[0]).keys()))
        writer.writeheader()
        for row in rows:
            writer.writerow(asdict(row))


def summarize(rows: list[TrialRow]) -> None:
    for rule in RULES:
        subset = [row for row in rows if row.rule == rule]
        print(f"\n[{rule}]")
        for key in ("record_edge_auc",) + MODEL_NAMES + ("clustering", "mean_shortest_path", "diameter", "growth_exponent"):
            values = np.asarray([getattr(row, key) for row in subset], dtype=float)
            print(f"{key:20s} {values.mean():.4f} +/- {values.std(ddof=1):.4f}")
        winners = Counter(max(MODEL_NAMES[:-1], key=lambda name: getattr(row, name)) for row in subset)
        low_dim = sum(winners[name] for name in ("euclid_1", "euclid_2", "euclid_3"))
        any_euclid = low_dim + winners["euclid_8"]
        print("winner_counts", dict(winners))
        print(f"low_dim_euclidean_wins={low_dim}/{len(subset)}")
        print(f"any_euclidean_wins={any_euclid}/{len(subset)}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seeds", type=int, default=30)
    parser.add_argument("--nodes", type=int, default=64)
    parser.add_argument("--degree", type=int, default=4)
    parser.add_argument("--epochs", type=int, default=80)
    parser.add_argument("--swaps-per-epoch", type=int, default=8)
    parser.add_argument("--replicas", type=int, default=8)
    parser.add_argument("--optim-steps", type=int, default=150)
    parser.add_argument("--out-csv", type=Path, default=Path("rm01e_trials.csv"))
    args = parser.parse_args()

    rows = [run_trial(rule, seed, args) for rule in RULES for seed in range(args.seeds)]
    write_rows(rows, args.out_csv)
    summarize(rows)


if __name__ == "__main__":
    main()
